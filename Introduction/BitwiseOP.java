package Introduction;

public class BitwiseOP {
    public static void main(String[] args) {
        int a=12;
        int b=7;
        System.out.println(a&b);
        System.out.println(a|b);
        System.out.println(a^b);
        System.out.println(~a);
        System.out.println(a<<2);
        System.out.println(a>>2);
    }
}
